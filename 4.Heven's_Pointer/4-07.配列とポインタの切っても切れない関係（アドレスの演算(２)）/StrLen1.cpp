#include <iostream>
using namespace std;

size_t StrLen(const char* str)
{
	size_t i;
	for (i = 0; str[i] != '\0'; ++i)
	{
		//何もしない
	}
	return i;
}

void ShowLength(const char* str)
{
	cout << "文字列「" << str << "」の長さは " <<endl
		 << str << endl << str + 1 << endl << str[1] << endl 
		 << &str << endl << &str + 1 << endl << &str[1] << endl 
		 << *str << endl << *str + 1 << endl /*できない。 << *str[1]*/ << endl
		 << StrLen(str) << "バイトです。" << endl;
}

int main()
{
	ShowLength("Hello");
} 

